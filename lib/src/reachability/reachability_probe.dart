/// عقد فحص الوصول الفعلي للإنترنت (reachability).
///
/// connectivity_plus تخبرك بواجهة الشبكة فقط (متصّل بواي فاي مثلًا)،
/// لا بوجود إنترنت فعلي — الشبكات المقصورة (captive portal) تظهر «متصلًا».
/// هذا العقد يتيح فحصًا حقيقيًا قبل اعتبار الاتصال متاحًا.
abstract interface class ReachabilityProbe {
  /// هل يمكن الوصول للإنترنت فعلًا؟ يجب أن يعيد false عند الفشل
  /// ولا يرمي استثناءً.
  Future<bool> isReachable();
}
